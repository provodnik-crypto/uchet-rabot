/**
 * Все тексты обучения и «Что нового» — здесь. Править можно только строки в кавычках.
 *
 * Шаг обучения подсвечивает элемент экрана (target) и показывает подсказку (text):
 *   kind: 'next' — кнопка «Далее»;
 *   kind: 'tap'  — подсказка просит нажать подсвеченную кнопку; обучение продолжится на следующем экране;
 *   free: true   — экран не затемняется, подсказка внизу (когда нажимать нужно рядом с подсвеченным).
 * Если нужного элемента сейчас нет на экране, внизу видна строка с подсказкой и «Пропустить».
 */

export type TourStep = {
  target: string;
  text: string;
  kind: 'next' | 'tap';
  /** Без затемнения: нажимать нужно не на подсвеченное, а рядом (например, на найденную работу). */
  free?: boolean;
};
